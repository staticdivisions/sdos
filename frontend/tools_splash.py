# Render the frontend's boot frame (default look, no glow, no progress bar) and emit
# splash/logo.h for the initramfs framebuffer splash, so boot -> UI is seamless.
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
os.environ['SDUI_MOCK'] = '1'; os.environ.setdefault('SDL_VIDEODRIVER', 'offscreen')
from sdui import main as M, device, look as LK, sdl
from sdui.gfx import Gfx
from sdui.app import App
from PIL import Image
out = sys.argv[1]
W, H = 640, 480
win, ren, W, H = M.setup_sdl(W, H, False, software=True)
g = Gfx(ren, W, H); g.glow = lambda *a, **k: None
app = App(g, device.make(), shot=True); app.set_look(dict(LK.DEFAULT))
app.jump_to('boot')
c = app.c
orig_rrect, orig_fill = g.rrect, g.fill
def rrect(x, y, w, h, r, col, a=1.0, *k, **kw):
    if h <= 2.5: return            # skip the progress track
    return orig_rrect(x, y, w, h, r, col, a, *k, **kw)
def fill(x, y, w, h, col, a=1.0, *k, **kw):
    if h <= 2.5: return            # skip the progress fill
    return orig_fill(x, y, w, h, col, a, *k, **kw)
g.rrect, g.fill = rrect, fill
sdl.SetRenderDrawColor(ren, 0, 0, 0, 255); sdl.RenderClear(ren)
app.render(); app.render()
png = out + '/boot_frame.png'; M.save_png(ren, W, H, png)
im = Image.open(png).convert('RGB'); bg = im.getpixel((2, 2))
px = im.load(); xs = []; ys = []
for y in range(H):
    for x in range(W):
        if px[x, y] != bg: xs.append(x); ys.append(y)
x0, x1, y0, y1 = max(min(xs) - 2, 0), min(max(xs) + 3, W), max(min(ys) - 2, 0), min(max(ys) + 3, H)
crop = im.crop((x0, y0, x1, y1)); crop.save(out + '/logo.png')
w, h = crop.size; data = crop.tobytes()
with open(out + '/logo.h', 'w') as f:
    f.write('/* generated by frontend/tools_splash.py from the boot screen (default look) */\n')
    f.write('#define LOGO_W %d\n#define LOGO_H %d\n#define LOGO_X %d\n#define LOGO_Y %d\n#define REF_W %d\n#define REF_H %d\n' % (w, h, x0, y0, W, H))
    f.write('#define BG_R %d\n#define BG_G %d\n#define BG_B %d\n' % bg)
    f.write('static const unsigned char logo_rgb[%d] = {\n' % len(data))
    for i in range(0, len(data), 24):
        f.write(','.join(str(b) for b in data[i:i + 24]) + ',\n')
    f.write('};\n')
print('logo', w, h, 'at', x0, y0, 'bg', bg)
